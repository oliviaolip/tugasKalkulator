import 'dart:core';

class kalkulator {
  //penjumlahan
  double tambah(double bil1, double bil2) {
    return bil1 + bil2;
  }

  //pengurangan
  double kurang(double bil1, double bil2) {
    return bil1 - bil2;
  }

  //perkalian
  double kali(double bil1, double bil2) {
    return bil1 * bil2;
  }

  //pembagian
  double bagi(double bil1, double bil2) {
    return bil1 / bil2;
  }
}